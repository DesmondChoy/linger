def parse_sections(source: Path = DEFAULT_SOURCE) -> tuple[ParsedChapter, ...]:
    """Extract audited line ranges without reflowing or guessing boundaries."""
    raw = source.read_bytes()
    if sha256(raw) != SOURCE_SHA256:
        raise CorpusBuildError("unexpected Story of My Life source SHA-256")
    lines = raw.decode("utf-8").replace("\r\n", "\n").replace("\r", "\n").split("\n")
    if len(lines) != 13667:
        raise CorpusBuildError("Story of My Life source line count changed")
    markers = {
        30: "*** START OF THE PROJECT GUTENBERG EBOOK THE STORY OF MY LIFE ***",
        101: " TABLE OF CONTENTS",
        118: "I. THE STORY OF MY LIFE",
        3575: "II. LETTERS(1887-1901)",
        3581: "II. LETTERS(1887-1901)",
        3656: "  LETTERS (1887-1901)",
        7553: "III: A SUPPLEMENTARY ACCOUNT OF HELEN KELLER'S LIFE AND EDUCATION",
        13312: "THE END",
        13317: "*** END OF THE PROJECT GUTENBERG EBOOK THE STORY OF MY LIFE ***",
    }
    for number, marker in markers.items():
        if lines[number - 1] != marker or lines.count(marker) != (2 if number in (3575, 3581) else 1):
            raise CorpusBuildError(f"Story of My Life marker changed at line {number}")
    parsed = []
    for number, section in enumerate(SECTIONS, 1):
        if lines[section.heading_line - 1] != section.source_heading:
            raise CorpusBuildError(f"section heading changed at line {section.heading_line}")
        if not lines[section.body_start - 1].strip() or not lines[section.end - 1].strip():
            raise CorpusBuildError(f"section {number} body boundary changed")
        if lines[section.end].strip():
            raise CorpusBuildError(f"section {number} no longer ends before a blank separator")
        body = "\n".join(lines[section.body_start - 1:section.end]) + "\n"
        parsed.append(ParsedChapter(
            number=number,
            title=section.title,
            slug=section.slug,
            markdown_heading=section.title,
            routing_description=section.description,
            characters=section.characters,
            locations=section.locations,
            retrieval_cues=section.cues,
            source_lines=(section.source_start, section.end),
            body_lines=(section.body_start, section.end),
            body=body,
        ))
    return tuple(parsed)


